# Rebuild assets/js/content.js ----------------------------------------------
# The website reads i18n/strings.csv, data/verses.csv and data/sample-public.json.
# On GitHub Pages (or with R/serve_local.R) it reads those files directly.
# When index.html is opened by double-click (file://), browsers block that,
# so the page uses a copy stored in assets/js/content.js.
# Run this script after editing the CSV/JSON files so both stay identical.

read_txt <- function(path) paste(readLines(path, encoding = "UTF-8", warn = FALSE), collapse = "\n")

content <- list(
  strings = read_txt("i18n/strings.csv"),
  verses  = read_txt("data/verses.csv"),
  sample  = read_txt("data/sample-public.json"),
  member  = read_txt("data/sample-member.json"),
  lists   = read_txt("data/sample-lists.json")
)

# install.packages("jsonlite")   # once
js <- paste0(
  "/* Generated by R/build_content.R - do not edit by hand */\n",
  "window.SITE_CONTENT = ",
  jsonlite::toJSON(content, auto_unbox = TRUE, pretty = TRUE),
  ";\n"
)
writeLines(js, "assets/js/content.js", useBytes = TRUE)
message("assets/js/content.js updated")
